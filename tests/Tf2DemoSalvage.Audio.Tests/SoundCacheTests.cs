    /// <summary>A cache over an install that answers a one-sample wave for whatever it has.</summary>
    /// <param name="reads">Records every path asked for, in order.</param>
    /// <param name="has">Which paths exist; everything, by default.</param>
    /// <param name="capacityBytes">The cache's cap.</param>
    /// <param name="offFrame">Where an in-play load is handed; null keeps it on the caller.</param>
    private static SoundCache Cache(
        List<string> reads, Func<string, bool>? has = null, long capacityBytes = SoundCache.CapacityBytes, Action<Action>? offFrame = null) =>
        new(NullLogger.Instance, capacityBytes)
        {
            OffFrame = offFrame,
            Read = path =>
            {
                reads.Add(path);

                return has is null || has(path) ? OneSample : null;
            },
        };

    /// <summary>A minimal 16-bit mono RIFF/WAVE carrying a single sample.</summary>
    private static byte[] OneSample => WaveBytes(16, 1, 22050, [0x01, 0x00]);

    /// <summary>A minimal RIFF/WAVE file, written by hand from the format rather than our reader.</summary>
    internal static byte[] WaveBytes(int bits, int channels, int rate, byte[] data)
    {
        int blockAlign = channels * ((bits + 7) / 8);
        List<byte> file = [];

        void Ascii(string text) => file.AddRange(Encoding.ASCII.GetBytes(text));

        void U32(int value)
        {
            byte[] four = new byte[4];
            BinaryPrimitives.WriteUInt32LittleEndian(four, (uint)value);
            file.AddRange(four);
        }

        void U16(int value)
        {
            byte[] two = new byte[2];
            BinaryPrimitives.WriteUInt16LittleEndian(two, (ushort)value);
            file.AddRange(two);
        }

        Ascii("RIFF");
        U32(36 + data.Length);
        Ascii("WAVE");

        Ascii("fmt ");
        U32(16);
        U16(1);
        U16(channels);
        U32(rate);
        U32(rate * blockAlign);
        U16(blockAlign);
        U16(bits);

        Ascii("data");
        U32(data.Length);
        file.AddRange(data);

        return [.. file];
    }
