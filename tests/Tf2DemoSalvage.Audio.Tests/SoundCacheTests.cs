using System.Collections.Generic;
using System.Text;

using Microsoft.Extensions.Logging.Abstractions;

using Tf2DemoSalvage.Audio;

namespace Tf2DemoSalvage.Audio.Tests;

/// <summary>
/// Decoding a named sound once, and moving every decode out of the frame that would have paid for it.
/// </summary>
/// <remarks>
/// **The engine owns this and reaches it through an interface** — <c>IEngineSound</c> declares
/// <c>PrecacheSound</c>, <c>IsSoundPrecached</c> and <c>PrefetchSound</c> together
/// (<c>src/public/engine/IEngineSound.h:89-91</c>), and game code asks rather than holding samples:
/// <c>CBaseEntity::PrecacheSound</c> is one line, <c>enginesound-&gt;PrecacheSound( name, true )</c>
/// at <c>SoundEmitterSystem.cpp:1507</c>.
///
/// Ours was <c>MainForm.Sample</c> with <c>_soundCache</c>, <c>_soundsUnopened</c> and
/// <c>_precaching</c> beside it, so **none of it had a test**: reaching it needed an STA thread, a
/// device and a TF2 install (B188, B184).
///
/// The files here are hand-built RIFF/WAVE rather than produced by our own writer — a fixture
/// generated by the code under test proves the two agree and nothing else
/// (<c>docs/memory/fixtures-are-the-weak-point.md#put-the-real-file-in-the-fixture</c>).
/// </remarks>
public sealed class SoundCacheTests
{
    [Test]
    public void Sample_WithNoReadSource_IsSilentRatherThanThrowing()
    {
        // **Every frame on a machine with no TF2 takes this path.** The viewer is meant to open a
        // demo without the game installed, so an absent archive set is an ordinary state rather
        // than an error — and the cache is asked for sounds from the first tick played.
        SoundCache cache = new(NullLogger.Instance);

        cache.Sample("weapons/shotgun_shoot.wav").ShouldBeNull();
    }

    [Test]
    public void Sample_ForTheSameNameTwice_ReadsTheFileOnce()
    {
        // **The whole reason the type exists.** A decode is a VPK read plus a full decode, on the
        // thread that draws — so a second read is a second freeze.
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        cache.Sample("ambient/indoors.wav");
        cache.Sample("ambient/indoors.wav");

        reads.Count.ShouldBe(1);
    }

    /// <remarks>
    /// One sample per <c>CSfxTable</c>: `S_FindName` (engine.dll FUN_18002b290) keys the whole name through the file-name
    /// table, which lower-cases and fixes separators, so these are one sound — and a stop naming one matches the voice
    /// started by the other, as `S_AlterChannel` matches by sfx (B545). The `#` is part of the key.
    /// </remarks>
    [TestCase("#Music/Song.wav", "#music\\song.wav", 1)]
    [TestCase("#music/song.wav", "music/song.wav", 2)]
    public void Sample_ForTwoSpellingsOfOneSfx_IsOneSample(string first, string second, int expectedReads)
    {
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        SoundSample? one = cache.Sample(first);
        SoundSample? two = cache.Sample(second);

        reads.Count.ShouldBe(expectedReads);

        // A record struct, so "the same sample" is the decode the two share, which is what a stop matches on.
        one.ShouldNotBeNull();
        two.ShouldNotBeNull();
        two.Value.Pcm16.Equals(one.Value.Pcm16).ShouldBe(expectedReads == 1);
    }

    [Test]
    public void Sample_ForTwoDifferentNames_ReadsEachOfThem()
    {
        // **The control for the case above**, without which "reads once" is indistinguishable from
        // "reads once ever" — a cache keyed on nothing would pass the first test and silence the
        // whole match.
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        cache.Sample("ambient/indoors.wav");
        cache.Sample("ambient/outdoors.wav");

        reads.Count.ShouldBe(2);
    }

    [Test]
    public void Sample_ForANameTheInstallLacks_IsRememberedRatherThanRetried()
    {
        // A missing sound must not be looked for sixty times a second — that buries the log in one
        // repeated line, which is how a real missing asset stops being noticeable.
        //
        // **Counted as "reads AFTER the first play" rather than as a total**, because a miss is not
        // one read: `SoundFile.Open` walks the containers a sound may ship in, so one absent
        // `.wav` costs a lookup per container. The first version asserted a total of 1 and failed
        // at 2 — the fixture was measuring the container fallback and calling it a retry.
        List<string> reads = [];
        SoundCache cache = Cache(reads, has: _ => false);

        cache.Sample("weapons/never_shipped.wav").ShouldBeNull();

        reads.ShouldNotBeEmpty("the first play must actually look for it");
        reads.Clear();

        for (int play = 0; play < 4; play++)
        {
            cache.Sample("weapons/never_shipped.wav").ShouldBeNull();
        }

        reads.ShouldBeEmpty();
        cache.Unopened.ShouldBe(1);
    }

    [Test]
    public void Sample_ForANameCarryingSoundchars_ReadsThePathWithoutThem()
    {
        // **Valve's prefixes are instructions to the engine, not part of the path** — ')' spatialised,
        // '#' a stream, and the rest. Left on, every one of them is a file that does not exist, so
        // the observable is the path actually asked for rather than whether a sample came back.
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        cache.Sample(")ambient/indoors.wav");

        reads.ShouldBe(["sound/ambient/indoors.wav"]);
    }

    [Test]
    public void Sample_ForAPlainName_ReadsItUnchanged()
    {
        // The control for the strip: a name with no soundchars must arrive whole. Without this,
        // an implementation that chopped the first character off everything would pass the pair
        // above.
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        cache.Sample("ambient/indoors.wav");

        reads.ShouldBe(["sound/ambient/indoors.wav"]);
    }

    [Test]
    public void Precache_OverAMixedList_SaysWhatArrivedAndWhatDidNot()
    {
        // **Both numbers, because they answer different questions.** The gap between them is how
        // many sounds the install could not supply, which is the difference between "the precache
        // worked" and "the precache found nothing to do" — one number cannot say which.
        SoundCache cache = Cache([], has: path => path.Contains("indoors", StringComparison.Ordinal));

        PrecacheResult result = cache.Precache(
            ["ambient/indoors.wav", "ambient/outdoors.wav", "ambient/nowhere.wav"]);

        result.Named.ShouldBe(3);
        result.Decoded.ShouldBe(1);
    }

    [Test]
    public void Precache_ForANameAlreadyDecoded_DoesNotReadItAgain()
    {
        // A precache runs after the soundscape catalog is read, and the two lists overlap. Reading
        // the overlap twice is the cost this type exists to remove.
        List<string> reads = [];
        SoundCache cache = Cache(reads);

        cache.Sample("ambient/indoors.wav");
        cache.Precache(["ambient/indoors.wav"]);

        reads.Count.ShouldBe(1);
    }

    /// <remarks>
    /// **What the cache holds, and how often playback paid for a decode** (finding 80: the cache retained 650 MB on f12).
    /// The bytes are the decoded samples it keeps, split by the container they came from, because only a WAV can be held
    /// as 16-bit exactly. A miss is a decode outside a precache, which is a freeze in the frame that asked. One precached
    /// one-sample WAV and one asked for during play: two held, two bytes each (a WAV is held as 16-bit), one miss.
    /// </remarks>
    [Test]
    public void Held_APrecachedSoundAndOneAskedForInPlay_CountsBytesByContainerAndOneMiss()
    {
        SoundCache cache = Cache([]);

        cache.Precache(["ambient/indoors.wav"]);
        cache.Sample("ambient/outdoors.wav");
        cache.Sample("ambient/outdoors.wav");

        cache.Held.ShouldBe(new SoundCacheHeld(Sounds: 2, WaveBytes: 4, Mp3Bytes: 0, Misses: 1));
    }

    /// <remarks>
    /// **The cache is bounded, least recently used out first** (finding 80). A cap of three one-sample WAVs (two bytes each)
    /// holds three: asking for a fourth evicts the one used longest ago, and asking for that one again decodes it again, as
    /// a miss, to the identical samples. The one asked for most recently survives.
    /// </remarks>
    [Test]
    public void Sample_PastTheCap_EvictsTheLeastRecentlyUsedAndRedecodesItIdentically()
    {
        List<string> reads = [];
        SoundCache cache = Cache(reads, capacityBytes: 6);

        short[] first = cache.Sample("a.wav")!.Value.Pcm16.ToArray();
        cache.Sample("b.wav");
        cache.Sample("c.wav");
        cache.Sample("a.wav");
        cache.Sample("d.wav");

        cache.Held.Sounds.ShouldBe(3, "b, the least recently used, went");
        reads.Clear();

        cache.Sample("a.wav");
        reads.ShouldBeEmpty("a was used recently and stayed");

        cache.Sample("b.wav")!.Value.Pcm16.ToArray().ShouldBe(first);
        reads.ShouldBe(["sound/b.wav"], "b was evicted, so it is read again");
        cache.Held.Misses.ShouldBe(5, "a, b, c and d once each, and b again");
        cache.Held.WaveBytes.ShouldBe(6);
    }

    /// <remarks>A miss is a decode in the frame; a name the install cannot open decodes nothing, so it is no miss (finding 80).</remarks>
    [Test]
    public void Held_ANameTheInstallCannotOpen_IsNoMiss()
    {
        SoundCache cache = Cache([], has: path => !path.Contains("missing", StringComparison.Ordinal));

        cache.Sample("missing.wav");
        cache.Sample("present.wav");

        cache.Unopened.ShouldBe(1, "the control: the missing name was asked for");
        cache.Held.Misses.ShouldBe(1);
    }

    /// <remarks>
    /// **A first play in the frame reads nothing on the caller** (B568, finding 90). The engine's mixer under
    /// `snd_async_fullyasync` or an async-load source does not mix a sound until its data arrives, and kicks the load
    /// instead (engine.dll FUN_18004bc10). So the first ask answers silence and hands one load away; the answer arrives on
    /// the next ask after the load ran, counted off the frame and not as a decode in play.
    /// </remarks>
    [Test]
    public void Sample_InPlayWithAnOffFrameLoader_ReadsNothingOnTheCallerAndAnswersOnceLoaded()
    {
        List<string> reads = [];
        List<Action> jobs = [];
        SoundCache cache = Cache(reads, offFrame: jobs.Add);

        cache.Sample("a.wav").ShouldBeNull();
        reads.ShouldBeEmpty("the caller's thread read nothing");
        jobs.Count.ShouldBe(1);

        jobs[0]();

        cache.Sample("a.wav").ShouldNotBeNull();
        reads.ShouldBe(["sound/a.wav"]);
        cache.Held.ShouldBe(new SoundCacheHeld(Sounds: 1, WaveBytes: 2, Mp3Bytes: 0, Misses: 0, OffFrame: 1));
    }

    [Test]
    public void Sample_AskedAgainWhileItsLoadIsPending_QueuesNoSecondLoad()
    {
        List<Action> jobs = [];
        SoundCache cache = Cache([], offFrame: jobs.Add);

        cache.Sample("a.wav");
        cache.Sample("a.wav").ShouldBeNull("still loading");

        jobs.Count.ShouldBe(1);
    }

    /// <remarks>A load started on one level must not land in the next: a pakfile can shadow the path (B485).</remarks>
    [Test]
    public void Sample_ALoadFinishingAfterANewLevel_IsNotKept()
    {
        List<Action> jobs = [];
        SoundCache cache = Cache([], offFrame: jobs.Add);

        cache.Sample("a.wav");
        cache.Level(_ => OneSample);
        jobs[0]();

        cache.Sample("a.wav").ShouldBeNull("the old level's load was dropped, so this asks again");
        jobs.Count.ShouldBe(2);
        cache.Held.OffFrame.ShouldBe(0);
    }

    [Test]
    public void Sample_AnOffFrameLoadTheInstallCannotOpen_IsCountedOnceAndNotRetried()
    {
        List<Action> jobs = [];
        SoundCache cache = Cache([], has: _ => false, offFrame: jobs.Add);

        cache.Sample("gone.wav");
        jobs[0]();
        cache.Sample("gone.wav").ShouldBeNull();
        cache.Sample("gone.wav").ShouldBeNull();

        jobs.Count.ShouldBe(1);
        cache.Unopened.ShouldBe(1);
    }

    /// <remarks>A precache that decodes a name while its play-time load is in flight holds it once; the late load is dropped.</remarks>
    [Test]
    public void Sample_AnOffFrameLoadArrivingAfterAPrecacheHeldIt_IsNotHeldTwice()
    {
        List<Action> jobs = [];
        SoundCache cache = Cache([], offFrame: jobs.Add);

        cache.Sample("a.wav");
        cache.Precache(["a.wav"]);
        jobs[0]();
        cache.Sample("a.wav").ShouldNotBeNull();

        cache.Held.ShouldBe(new SoundCacheHeld(Sounds: 1, WaveBytes: 2, Mp3Bytes: 0, Misses: 0, OffFrame: 0));
    }

    [Test]
    public void Precache_WithAnOffFrameLoader_StillDecodesOnTheCaller()
    {
        // The control for the deferral: a precache is the load worker's, outside any frame, and must arrive complete.
        List<Action> jobs = [];
        SoundCache cache = Cache([], offFrame: jobs.Add);

        cache.Precache(["a.wav"]).Decoded.ShouldBe(1);

        jobs.ShouldBeEmpty();
        cache.Sample("a.wav").ShouldNotBeNull();
    }

    /// <remarks>
    /// **A second precache decodes only names no earlier precache of the level listed** (B570). It runs on the UI thread
    /// in `ViewerPresenter.Apply`; past the cap, re-asking for the first pass's names re-decoded every evicted one there.
    /// A cap of two one-sample WAVs, three precached, then the same three and one more: only the new one is read.
    /// </remarks>
    [Test]
    public void Precache_ASecondPassAfterTheCapEvicted_ReadsOnlyTheNewName()
    {
        List<string> reads = [];
        SoundCache cache = Cache(reads, capacityBytes: 4);

        cache.Precache(["a.wav", "b.wav", "c.wav"]);
        reads.Count.ShouldBe(3, "the control: the first pass read all three");
        reads.Clear();

        cache.Precache(["a.wav", "b.wav", "c.wav", "d.wav"]);

        reads.ShouldBe(["sound/d.wav"]);
    }

