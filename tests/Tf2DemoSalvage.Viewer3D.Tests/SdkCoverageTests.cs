    /// <summary>The network messages this project decodes.</summary>
    /// <remarks>
    /// All of them, which is not a boast: a demo carries no length prefixes, so a message this
    /// project could not read would stop the stream at that byte. "Decode must be total" is a rule
    /// here for that reason, and this is the assertion of it.
    /// </remarks>
    private static string[] ImplementedMessages() =>
    [
        "Tick", "StringCmd", "SetConVar", "SignonState", "Print", "ServerInfo", "SendTable",
        "ClassInfo", "SetPause", "CreateStringTable", "UpdateStringTable", "VoiceInit",
