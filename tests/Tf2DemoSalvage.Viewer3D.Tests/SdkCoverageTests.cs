        "LUMP_TEXINFO", "LUMP_FACES", "LUMP_LIGHTING", "LUMP_LEAFS", "LUMP_EDGES",
        "LUMP_SURFEDGES", "LUMP_MODELS", "LUMP_WORLDLIGHTS", "LUMP_LEAFFACES",
