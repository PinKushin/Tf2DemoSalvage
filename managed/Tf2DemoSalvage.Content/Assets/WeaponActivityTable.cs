/// <summary>
/// Valve's per-weapon activity tables — <c>CTFWeaponBase::ActivityOverride</c>.
/// </summary>
/// <remarks>
/// **A player's animations are named generically and rewritten by the weapon in hand.**
/// `CTFPlayerAnimState::TranslateActivity` (`tf_playeranimstate.cpp:124`) calls
/// `pWeapon->ActivityOverride( translateActivity, NULL )`, which walks the weapon's own
/// `acttable_t` — one table per role, twelve of them, in `tf_weaponbase.cpp:3660` onward. So
/// `ACT_MP_RELOAD_STAND` becomes `ACT_MP_RELOAD_STAND_PRIMARY` in a scattergun's hands and
/// `ACT_MP_RELOAD_STAND_SECONDARY` in a pistol's, and a model declares only the rewritten names.
///
/// **It is a TABLE and not a suffix rule, which is why this is transcribed rather than computed.**
/// Three entries in the primary table alone break any pattern you could write:
///
/// <code>
///   { ACT_MP_STAND_IDLE,                ACT_MP_STAND_PRIMARY,        false },  // IDLE → PRIMARY
///   { ACT_MP_CROUCH_DEPLOYED,           ACT_MP_CROUCHWALK_DEPLOYED,  false },  // CROUCH → CROUCHWALK
///   { ACT_MP_ATTACK_STAND_PRIMARYFIRE,  ACT_MP_ATTACK_STAND_PRIMARY, false },  // PRIMARYFIRE → PRIMARY
/// </code>
///
/// A first attempt at B284 appended the role as a string. That happens to be right for the reload
/// and jump-land families and wrong for every attack, which is a silent wrongness: an activity that
/// resolves to no sequence draws no gesture and logs nothing.
///
/// **Generated from the SDK, and a conformance test regenerates it.** The rows below were extracted
/// from `tf_weaponbase.cpp` rather than typed, and `WeaponActivityConformanceTests` parses the same
/// file and asserts the two agree — so this cannot drift from Valve without a red test, which is
/// the same arrangement `SdkCoverageTests` uses for the shader and lump denominators.
///
/// **Not implemented: the two overrides that sit either side of this one.**
/// `CTFPlayerAnimState::ActivityOverride` applies the player's own table first (the kart and taunt
/// states), and `CEconItemView::GetActivityOverride` applies a per-item one afterwards, which is
