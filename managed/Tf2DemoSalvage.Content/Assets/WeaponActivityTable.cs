    public static int Count => Rows.Length;

    /// <summary>The roles the table names.</summary>
    public static IReadOnlyCollection<string> Roles => ByRole.Keys;

    /// <summary>Rewrites one activity for the weapon role holding it.</summary>
    /// <param name="role">The weapon's role — <c>PRIMARY</c>, <c>MELEE</c>, <c>ITEM2</c>.</param>
    /// <param name="activity">The generic activity the animation state asked for.</param>
    /// <returns>The weapon's own name for it, or <paramref name="activity"/> unchanged.</returns>
    /// <remarks>
    /// **Unchanged is the right answer for a miss**, and it is Valve's:
    /// `CBaseCombatWeapon::ActivityOverride` returns what it was given when the table has no row
    /// (`basecombatweapon_shared.cpp`), so an activity no weapon rewrites — a flinch — reaches the
    /// model under its own name.
    /// </remarks>
    public static string Override(string role, string activity)
    {
        ArgumentNullException.ThrowIfNull(role);
        ArgumentNullException.ThrowIfNull(activity);

        return ByRole.TryGetValue(role, out Dictionary<string, string>? table) &&
            table.TryGetValue(activity, out string? mapped)
                ? mapped
                : activity;
    }

    /// <summary>Every row for one role, for the conformance test to compare against.</summary>
    /// <param name="role">The role.</param>
    /// <returns>Its table, or an empty one.</returns>
    public static IReadOnlyDictionary<string, string> For(string role)
    {
        ArgumentNullException.ThrowIfNull(role);

        return ByRole.TryGetValue(role, out Dictionary<string, string>? table)
            ? table
            : new Dictionary<string, string>(StringComparer.Ordinal);
    }

    /// <summary>Indexes the rows by role and source activity.</summary>
    /// <returns>The lookup.</returns>
    /// <remarks>
    /// **The FIRST row for a pair wins, which is what a linear table walk does.**
    /// `ActivityOverride` returns on its first match, so a table listing a source twice uses the
    /// earlier entry — and at least one of Valve's does.
    /// </remarks>
    private static Dictionary<string, Dictionary<string, string>> Build()
    {
        Dictionary<string, Dictionary<string, string>> built = new(StringComparer.Ordinal);

        foreach (string row in Rows)
        {
            string[] parts = row.Split('|');

            if (parts.Length != 3)
            {
                continue;
            }

            if (!built.TryGetValue(parts[0], out Dictionary<string, string>? table))
            {
                table = new Dictionary<string, string>(StringComparer.Ordinal);
                built[parts[0]] = table;
            }

            _ = table.TryAdd(parts[1], parts[2]);
        }

        return built;
    }
